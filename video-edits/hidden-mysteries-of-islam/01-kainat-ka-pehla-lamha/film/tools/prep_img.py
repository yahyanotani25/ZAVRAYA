#!/usr/bin/env python3
"""assets/img/* -> gfx/img/<key>.jpg (<=4096 px, sRGB JPEG) + film/src/assets.js (IMG map). Re-run when new assets arrive."""
import os, glob, json
from PIL import Image
Image.MAX_IMAGE_PIXELS = None
S = '/tmp/claude-0/-home-user-ZAVRAYA/11d60b1e-ec95-526d-bd06-3bd05d7e3343/scratchpad'
MAP = [  # (filename substring, key)
 ('einstein_1921', 'einstein1921'), ('einstein_1947', 'einstein1947'), ('einstein_general_relativity_1916', 'einsteinPaper1916'), ('einstein_blackboard', 'einsteinBoard'),
 ('lemaitre', 'lemaitre'), ('millikan', 'millikanLemaitreEinstein'), ('edwin_hubble', 'hubble'), ('hooker', 'hooker'), ('russell', 'russell'),
 ('aristotle_bust', 'aristotle'), ('school_of_athens', 'schoolOfAthens'), ('holmdel_horn', 'hornAntenna'), ('hawking', 'hawking'), ('jastrow', 'jastrow'),
 ('four_pigeons', 'pigeon1'), ('pigeon_in_flight', 'pigeon2'), ('elephant', 'elephant'), ('climbers', 'climbers'), ('mountain', 'mountain'), ('crt_television', 'crtTV'), ('banknote', 'banknote'),
 ('hubble_ultra_deep_field', 'hudf'), ('extreme_deep_field', 'xdf'), ('jwst_first_deep_field', 'jwstDeep'), ('pillars_of_creation', 'pillars'), ('cosmic_cliffs', 'cosmicCliffs'),
 ('andromeda', 'andromeda'), ('whirlpool', 'm51'), ('ngc1300', 'ngc1300'), ('sombrero', 'sombrero'), ('milky_way_panorama', 'milkywayPano'), ('wmap_timeline', 'wmapTimeline'), ('cmb_ilc_mollweide', 'cmbMollweide'),
]
os.makedirs(f'{S}/gfx/img', exist_ok=True)
img = {'placeholder': '/gfx/img/placeholder.jpg'}; used = set()
for f in sorted(glob.glob(f'{S}/assets/img/*')):
    b = os.path.basename(f).lower()
    if b.startswith('b01_') or b.endswith(('.svg', '.json')): continue
    key = next((k for sub, k in MAP if sub in b), None)
    if key is None: key = os.path.splitext(b)[0]
    n = 2
    base = key
    while key in used: key = f'{base}_{n}'; n += 1
    used.add(key)
    out = f'{S}/gfx/img/{key}.jpg'
    if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(f):
        try:
            im = Image.open(f)
            if im.mode in ('I;16', 'I', 'F'): im = im.point(lambda v: v / 256).convert('L')
            im = im.convert('RGB'); im.thumbnail((4096, 4096), Image.LANCZOS); im.save(out, quality=92)
        except Exception as e:
            print('FAIL', b, e); continue
    w, h = Image.open(out).size
    img[key] = f'/gfx/img/{key}.jpg'; print(f'{key:28s} {w}x{h}  <- {os.path.basename(f)}')
img.setdefault('russell_2', img.get('russell', img['placeholder']))
if os.path.exists(f'{S}/gfx/img/lemaitre_crop.jpg') and 'lemaitre' in img:
    img['lemaitreWide'] = img['lemaitre']; img['lemaitre'] = '/gfx/img/lemaitre_crop.jpg'
js = "// AUTO-GENERATED by tools/prep_img.py — web-ready images (<=4096 px). Use IMG.<key>; fall back to IMG.placeholder if a key is missing.\nexport const IMG = " + json.dumps(img, indent=1) + ";\n"
open(f'{S}/film/src/assets.js', 'w').write(js)
